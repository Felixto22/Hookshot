"""(felix) SMAA 1x (Jimenez et al., MIT: LICENSE.txt) as three compute shaders for the TAAU stand-in (vk_draw.cpp smaa_pass).

SMAA.hlsl is the reference file as published, in its GLSL 4 mode, pasted into each shader below with its three `discard`s (no
edge: the pixel's edges stay zero) turned into returns, since a compute shader writes every pixel itself. Run from anywhere:
    python3 gpu/vk/shaders/smaa/make_smaa.py      (needs glslangValidator)
It writes ../smaa_edges.comp, ../smaa_weights.comp, ../smaa_blend.comp and their *_comp_spv.h."""
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(HERE)
ref = open(os.path.join(HERE, "SMAA.hlsl"), encoding="latin-1").read()
assert ref.count("discard;") == 3
ref = ref.replace("discard;", "return float2(0.0, 0.0);")
ref = ref.encode("ascii", "replace").decode("ascii")   # (a few Latin-1 characters in its comments)
# (a compute shader has no implicit level of detail: the GLSL mode's texture() reads at level 0, as the rest of the file does)
for a, b in (("#define SMAASample(tex, coord) texture(tex, coord)", "#define SMAASample(tex, coord) textureLod(tex, coord, 0.0)"),
             ("#define SMAASamplePoint(tex, coord) texture(tex, coord)", "#define SMAASamplePoint(tex, coord) textureLod(tex, coord, 0.0)"),
             ("#define SMAASampleOffset(tex, coord, offset) texture(tex, coord, offset)",
              "#define SMAASampleOffset(tex, coord, offset) textureLodOffset(tex, coord, 0.0, offset)")):
    assert ref.count(a) == 1
    ref = ref.replace(a, b)

HEAD = """#version 450
// (felix) generated by smaa/make_smaa.py from SMAA.hlsl (MIT, Jorge Jimenez et al.: smaa/LICENSE.txt): do not edit
layout(local_size_x = 8, local_size_y = 8) in;
layout(push_constant) uniform P { vec4 metrics; } pc;   // (1/w, 1/h, w, h)
#define SMAA_GLSL_4
#define SMAA_PRESET_ULTRA
#define SMAA_RT_METRICS pc.metrics
"""

PASSES = {
    "smaa_edges": """
layout(binding = 0) uniform sampler2D color_tex;
layout(binding = 1, rgba8) uniform writeonly image2D edges_out;
void main() {
    const ivec2 g = ivec2(gl_GlobalInvocationID.xy);
    if (any(greaterThanEqual(vec2(g), pc.metrics.zw))) return;
    const vec2 texcoord = (vec2(g) + 0.5) * pc.metrics.xy;
    vec4 offset[3];
    SMAAEdgeDetectionVS(texcoord, offset);
    const vec2 e = SMAALumaEdgeDetectionPS(texcoord, offset, color_tex);
    imageStore(edges_out, g, vec4(e, 0.0, 0.0));
}
""",
    "smaa_weights": """
layout(binding = 0) uniform sampler2D edges_tex;
layout(binding = 1) uniform sampler2D area_tex;
layout(binding = 2) uniform sampler2D search_tex;
layout(binding = 3, rgba8) uniform writeonly image2D weights_out;
void main() {
    const ivec2 g = ivec2(gl_GlobalInvocationID.xy);
    if (any(greaterThanEqual(vec2(g), pc.metrics.zw))) return;
    const vec2 texcoord = (vec2(g) + 0.5) * pc.metrics.xy;
    vec2 pixcoord;
    vec4 offset[3];
    SMAABlendingWeightCalculationVS(texcoord, pixcoord, offset);
    const vec4 w = SMAABlendingWeightCalculationPS(texcoord, pixcoord, offset, edges_tex, area_tex, search_tex, vec4(0.0));
    imageStore(weights_out, g, w);
}
""",
    "smaa_blend": """
layout(binding = 0) uniform sampler2D color_tex;
layout(binding = 1) uniform sampler2D weights_tex;
layout(binding = 2, rgba16f) uniform writeonly image2D color_out;
void main() {
    const ivec2 g = ivec2(gl_GlobalInvocationID.xy);
    if (any(greaterThanEqual(vec2(g), pc.metrics.zw))) return;
    const vec2 texcoord = (vec2(g) + 0.5) * pc.metrics.xy;
    vec4 offset;
    SMAANeighborhoodBlendingVS(texcoord, offset);
    vec4 c = SMAANeighborhoodBlendingPS(texcoord, offset, color_tex, weights_tex);
    if (any(isnan(c)) || any(isinf(c))) c = textureLod(color_tex, texcoord, 0.0);
    imageStore(color_out, g, vec4(c.rgb, 1.0));
}
""",
}

for name, body in PASSES.items():
    comp = os.path.join(OUT, name + ".comp")
    with open(comp, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEAD + ref + "\n" + body)
    var = (name + "_COMP_SPV").upper()
    subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.3", "--vn", var, "-o",
                    os.path.join(OUT, name + "_comp_spv.h"), comp], check=True)
